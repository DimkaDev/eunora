import 'package:intl/intl.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:eunora/features/passport/models/passport_data.dart';
import 'package:eunora/features/passport/services/passport_chart_renderer.dart';
import 'package:eunora/features/symptom_log/data/symptom_library.dart';

class PassportPdfBuilder {
  static const double trendThreshold = 0.05; // 5% threshold for trend changes

  /// Pure function mapping PassportData to a pw.Document.
  /// Runs completely in-memory, making it fully unit-testable.
  static pw.Document build(PassportData data) {
    final pdf = pw.Document(
      title: "MenoSync Menopause Passport",
      author: "MenoSync",
    );

    // Formatter helpers
    final df = DateFormat('yyyy-MM-dd');
    final dtf = DateFormat('yyyy-MM-dd HH:mm');

    // Accent Colors
    final baseTextColor = PdfColor.fromInt(0xFF3A3A3A);
    final accentRuleColor = PdfColor.fromInt(0xFF9B8B7E);
    final headerBgColor = PdfColor.fromInt(0xFFFAF9F6);
    final successColor = PdfColor.fromInt(0xFF2E7D32); // Darker green for clinical readability
    final dangerColor = PdfColor.fromInt(0xFFC62828);
    final doseChangeBg = PdfColor.fromInt(0xFFFDF0ED);

    final fontStyleNormal = pw.TextStyle(color: baseTextColor, fontSize: 9);
    final fontStyleBold = pw.TextStyle(color: baseTextColor, fontSize: 9, fontWeight: pw.FontWeight.bold);

    // Collect dose change dates to pass to charts
    final List<DateTime> doseChangeDates = data.hrtHistory
        .where((h) => h.isDoseChangeMarker && h.changeDate != null)
        .map((h) => h.changeDate!)
        .toList();

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(32),
        header: (pw.Context context) {
          return pw.Container(
            alignment: pw.Alignment.centerRight,
            margin: const pw.EdgeInsets.only(bottom: 12),
            child: pw.Text(
              "MENOPAUSE PASSPORT · Generated by MenoSync · Page ${context.pageNumber} of ${context.pagesCount}",
              style: pw.TextStyle(color: PdfColors.grey500, fontSize: 8),
            ),
          );
        },
        footer: (pw.Context context) {
          return pw.Container(
            alignment: pw.Alignment.centerLeft,
            margin: const pw.EdgeInsets.only(top: 12),
            child: pw.Text(
              "Generated ${dtf.format(data.generatedAt)} · Data period: ${df.format(data.reportStart)} - ${df.format(data.reportEnd)} · ${data.totalEntries} total entries",
              style: pw.TextStyle(color: PdfColors.grey500, fontSize: 8),
            ),
          );
        },
        build: (pw.Context context) {
          // Precompute symptom statistics values
          // Only include if user has >= 1 logged entry
          final validStats = data.symptomStats.where((s) => s.daysLogged >= 1).toList();

          // Match categories to definitions
          final List<MapEntry<SymptomStatRow, SymptomCategory>> statsWithCategory = validStats.map((stat) {
            final def = kSymptomLibrary.firstWhere(
              (d) => d.label.toLowerCase() == stat.category.toLowerCase() || d.id == stat.category,
              orElse: () => const SymptomDefinition(
                id: '',
                label: '',
                category: SymptomCategory.physical,
                tier: SymptomTier.extended,
                inputMethod: '',
              ),
            );
            return MapEntry(stat, def.category);
          }).toList();

          final bool hasMoreThan8 = statsWithCategory.length > 8;

          final List<MapEntry<SymptomStatRow, SymptomCategory>> displayList;
          if (hasMoreThan8) {
            // Cap at 8 most-frequently logged symptoms
            final sortedByFreq = List<MapEntry<SymptomStatRow, SymptomCategory>>.from(statsWithCategory)
              ..sort((a, b) => b.key.daysLogged.compareTo(a.key.daysLogged));
            final top8 = sortedByFreq.take(8).toList();

            // Re-sort the top 8 by SymptomCategory order to preserve visual grouping
            displayList = top8..sort((a, b) => a.value.index.compareTo(b.value.index));
          } else {
            // Sort all by SymptomCategory order
            displayList = List<MapEntry<SymptomStatRow, SymptomCategory>>.from(statsWithCategory)
              ..sort((a, b) => a.value.index.compareTo(b.value.index));
          }

          return [
            // --- Section 1: Patient Profile & Title Block ---
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                  "MENOPAUSE PASSPORT",
                  style: pw.TextStyle(fontSize: 22, fontWeight: pw.FontWeight.bold, color: baseTextColor),
                ),
                pw.Text(
                  df.format(data.generatedAt),
                  style: pw.TextStyle(fontSize: 10, color: PdfColors.grey600),
                ),
              ],
            ),
            pw.SizedBox(height: 4),
            pw.Divider(color: accentRuleColor, thickness: 1.5),
            pw.SizedBox(height: 8),

            // Profile Information Table
            pw.Table(
              columnWidths: {
                0: const pw.FlexColumnWidth(1),
                1: const pw.FlexColumnWidth(2),
              },
              children: [
                _buildProfileRow("Patient Name/Initials:", data.displayName, fontStyleBold, fontStyleNormal),
                if (data.dateOfBirth != null)
                  _buildProfileRow("Date of Birth / Age:", "${df.format(data.dateOfBirth!)} (${DateTime.now().difference(data.dateOfBirth!).inDays ~/ 365} years)", fontStyleBold, fontStyleNormal),
                _buildProfileRow("Menopause Stage:", data.stage.toUpperCase(), fontStyleBold, fontStyleNormal),
                _buildProfileRow("Symptom Tracking Since:", df.format(data.firstLogDate), fontStyleBold, fontStyleNormal),
                _buildProfileRow("Report Period:", "${df.format(data.reportStart)} — ${data.reportEnd == null ? '' : df.format(data.reportEnd)} (${data.reportEnd.difference(data.reportStart).inDays} days)", fontStyleBold, fontStyleNormal),
                _buildProfileRow(
                  "Current HRT:",
                  data.currentHrt.isEmpty
                      ? "Not currently on HRT"
                      : data.currentHrt.map((h) => "${h.drugName} ${h.doseValue}${h.doseUnit} ${h.form} (since ${df.format(h.startDate)})").join('\n'),
                  fontStyleBold,
                  fontStyleNormal,
                ),
              ],
            ),
            pw.SizedBox(height: 12),

            // --- Medical Disclaimer ---
            pw.Container(
              padding: const pw.EdgeInsets.all(8),
              decoration: pw.BoxDecoration(
                border: pw.Border.all(color: PdfColors.grey400),
                borderRadius: const pw.BorderRadius.all(pw.Radius.circular(4)),
              ),
              child: pw.Text(
                "This report was generated from self-reported information entered into MenoSync. It has not been verified by a healthcare professional. It is intended to support conversation with your doctor — not to replace clinical assessment or diagnosis.",
                style: pw.TextStyle(fontSize: 8, fontStyle: pw.FontStyle.italic, color: baseTextColor),
              ),
            ),
            pw.SizedBox(height: 18),

            // --- Section 2: Symptom Statistics Summary ---
            _buildSectionHeader("Section 2: Symptom Statistics Summary", accentRuleColor, baseTextColor),
            pw.SizedBox(height: 8),
            if (displayList.isEmpty)
              pw.Text("No symptoms logged during this period.", style: fontStyleNormal)
            else ...[
              pw.Table(
                border: pw.TableBorder.all(color: PdfColors.grey300, width: 0.5),
                columnWidths: {
                  0: const pw.FlexColumnWidth(2),
                  1: const pw.FlexColumnWidth(1),
                  2: const pw.FlexColumnWidth(1),
                  3: const pw.FlexColumnWidth(1.2),
                  4: const pw.FlexColumnWidth(1.2),
                },
                children: [
                  pw.TableRow(
                    decoration: pw.BoxDecoration(color: headerBgColor),
                    children: [
                      _buildTableHeaderCell("Symptom Category"),
                      _buildTableHeaderCell("Days Logged"),
                      _buildTableHeaderCell("Avg Severity"),
                      _buildTableHeaderCell("Peak Day"),
                      _buildTableHeaderCell("Trend"),
                    ],
                  ),
                  ...displayList.map((entry) {
                    final stat = entry.key;
                    final String trendLabel;
                    final PdfColor trendColor;
                    if (stat.trend == 'Improving') {
                      trendLabel = "↓ Improving";
                      trendColor = successColor;
                    } else if (stat.trend == 'Worsening') {
                      trendLabel = "↑ Worsening";
                      trendColor = dangerColor;
                    } else {
                      trendLabel = "→ Stable";
                      trendColor = baseTextColor;
                    }

                    return pw.TableRow(
                      children: [
                        _buildTableCell(stat.category, fontStyleNormal),
                        _buildTableCell(stat.daysLogged.toString(), fontStyleNormal),
                        _buildTableCell("${stat.avgSeverity.toStringAsFixed(1)} / 5", fontStyleNormal),
                        _buildTableCell(stat.peakDay != null ? df.format(stat.peakDay!) : "N/A", fontStyleNormal),
                        _buildTableCell(trendLabel, pw.TextStyle(color: trendColor, fontSize: 9, fontWeight: pw.FontWeight.bold)),
                      ],
                    );
                  }),
                ],
              ),
              if (hasMoreThan8) ...[
                pw.SizedBox(height: 6),
                pw.Text(
                  "Additional less-frequent symptoms tracked — full log available in Section 6.",
                  style: pw.TextStyle(fontSize: 8, fontStyle: pw.FontStyle.italic, color: baseTextColor),
                ),
              ],
            ],
            pw.SizedBox(height: 18),

            // --- Section 3: Trend Charts ---
            _buildSectionHeader("Section 3: Trend Charts", accentRuleColor, baseTextColor),
            pw.SizedBox(height: 8),
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                PassportChartRenderer.renderHotFlashChart(
                  data: data.hotFlashFrequency,
                  doseChangeDates: doseChangeDates,
                  width: 250,
                  height: 120,
                ),
                PassportChartRenderer.renderSleepChart(
                  data: data.sleepQualityRollingAvg,
                  doseChangeDates: doseChangeDates,
                  width: 250,
                  height: 120,
                ),
              ],
            ),
            pw.SizedBox(height: 12),
            PassportChartRenderer.renderMoodChart(
              data: data.moodStackedWeekly,
              doseChangeDates: doseChangeDates,
              width: 512,
              height: 120,
            ),
            pw.SizedBox(height: 18),

            // --- Section 4: Patterns & Triggers ---
            _buildSectionHeader("Section 4: Patterns & Triggers", accentRuleColor, baseTextColor),
            pw.SizedBox(height: 4),
            pw.Text(
              "AI-identified personal patterns — for discussion with your healthcare provider.",
              style: pw.TextStyle(fontSize: 8.5, color: PdfColors.grey600),
            ),
            pw.SizedBox(height: 8),
            if (data.topPatterns.isEmpty)
              pw.Text(
                "Not enough data yet to identify personal patterns. Keep logging — patterns typically emerge after 2–3 weeks of consistent tracking.",
                style: fontStyleNormal,
              )
            else
              pw.Table(
                border: pw.TableBorder.all(color: PdfColors.grey300, width: 0.5),
                columnWidths: {
                  0: const pw.FlexColumnWidth(2),
                  1: const pw.FlexColumnWidth(3),
                  2: const pw.FlexColumnWidth(1.2),
                  3: const pw.FlexColumnWidth(1.2),
                },
                children: [
                  pw.TableRow(
                    decoration: pw.BoxDecoration(color: headerBgColor),
                    children: [
                      _buildTableHeaderCell("Trigger"),
                      _buildTableHeaderCell("Associated Effect"),
                      _buildTableHeaderCell("Correlation %"),
                      _buildTableHeaderCell("Data Points"),
                    ],
                  ),
                  ...data.topPatterns.map((pat) {
                    final String triggerText = pat.triggerId?.replaceAll('t_', '').toUpperCase() ?? 'TRIGGER';
                    return pw.TableRow(
                      children: [
                        _buildTableCell(triggerText, fontStyleNormal),
                        _buildTableCell(pat.label.split('(').first.trim(), fontStyleNormal),
                        _buildTableCell("${pat.correlationPercent}%", fontStyleNormal),
                        _buildTableCell("${pat.eventCount} events", fontStyleNormal),
                      ],
                    );
                  }),
                ],
              ),
            pw.SizedBox(height: 6),
            pw.Text(
              "⚠ These patterns are derived from self-reported data and are for informational purposes only. Correlation does not imply causation. Not a substitute for clinical assessment.",
              style: pw.TextStyle(fontSize: 7.5, color: PdfColors.grey600, fontStyle: pw.FontStyle.italic),
            ),
            pw.SizedBox(height: 18),

            // --- Section 5: HRT History & Impact ---
            _buildSectionHeader("Section 5: HRT History & Impact", accentRuleColor, baseTextColor),
            pw.SizedBox(height: 8),
            if (data.hrtHistory.isEmpty)
              pw.Text("No HRT dose changes recorded in this period.", style: fontStyleNormal)
            else
              pw.Table(
                border: pw.TableBorder.all(color: PdfColors.grey300, width: 0.5),
                columnWidths: {
                  0: const pw.FlexColumnWidth(1.2),
                  1: const pw.FlexColumnWidth(1.5),
                  2: const pw.FlexColumnWidth(1),
                  3: const pw.FlexColumnWidth(3),
                },
                children: [
                  pw.TableRow(
                    decoration: pw.BoxDecoration(color: headerBgColor),
                    children: [
                      _buildTableHeaderCell("Period"),
                      _buildTableHeaderCell("Drug / Dose"),
                      _buildTableHeaderCell("Duration"),
                      _buildTableHeaderCell("Observed Effect on Symptoms"),
                    ],
                  ),
                  ...data.hrtHistory.map((phase) {
                    if (phase.isDoseChangeMarker) {
                      final directionText = phase.changeDirection == 'increased' ? '↑ INCREASED' : '↓ DECREASED';
                      return pw.TableRow(
                        decoration: pw.BoxDecoration(color: doseChangeBg),
                        children: [
                          _buildTableCell(phase.changeDate != null ? df.format(phase.changeDate!) : "Dose Change", fontStyleBold),
                          _buildTableCell("$directionText to ${phase.dose}${phase.unit}", fontStyleBold),
                          _buildTableCell("-", fontStyleNormal),
                          _buildTableCell(phase.changeReason ?? "Dose adjustment", fontStyleNormal),
                        ],
                      );
                    }

                    return pw.TableRow(
                      children: [
                        _buildTableCell(phase.periodLabel, fontStyleNormal),
                        _buildTableCell(_formatHrtDrugDose(phase), fontStyleNormal),
                        _buildTableCell('${phase.durationDays} days', fontStyleNormal),
                        _buildTableCell(phase.observedEffect, fontStyleNormal),
                      ],
                    );
                  }),
                ],
              ),
            pw.SizedBox(height: 6),
            pw.Text(
              "Note: Before/after analysis shown only when ≥14 days of logged data exist in each phase and ≥7 entries per window.",
              style: pw.TextStyle(fontSize: 7.5, color: PdfColors.grey600, fontStyle: pw.FontStyle.italic),
            ),
            pw.SizedBox(height: 18),

            // --- Section 6: Full Log Table ---
            _buildSectionHeader("Section 6: Full Log Table", accentRuleColor, baseTextColor),
            pw.SizedBox(height: 8),
            if (data.fullLog.isEmpty)
              pw.Text("No entries logged in this period.", style: fontStyleNormal)
            else
              pw.Table(
                border: pw.TableBorder.all(color: PdfColors.grey300, width: 0.5),
                columnWidths: {
                  0: const pw.FlexColumnWidth(1.2),
                  1: const pw.FlexColumnWidth(1),
                  2: const pw.FlexColumnWidth(3),
                  3: const pw.FlexColumnWidth(1.5),
                  4: const pw.FlexColumnWidth(2),
                },
                children: [
                  pw.TableRow(
                    decoration: pw.BoxDecoration(color: headerBgColor),
                    children: [
                      _buildTableHeaderCell("Date"),
                      _buildTableHeaderCell("Time"),
                      _buildTableHeaderCell("Symptoms Logged"),
                      _buildTableHeaderCell("HRT Taken?"),
                      _buildTableHeaderCell("Triggers"),
                    ],
                  ),
                  ...data.fullLog.map((row) {
                    return pw.TableRow(
                      children: [
                        _buildTableCell(df.format(row.date), fontStyleNormal),
                        _buildTableCell(row.time, fontStyleNormal),
                        _buildTableCell(row.symptomsLogged, fontStyleNormal),
                        _buildTableCell(row.hrtTaken, fontStyleNormal),
                        _buildTableCell(row.triggers, fontStyleNormal),
                      ],
                    );
                  }),
                ],
              ),
          ];
        },
      ),
    );

    return pdf;
  }

  // --- Layout Helper Methods ---

  static pw.TableRow _buildProfileRow(
    String label,
    String value,
    pw.TextStyle labelStyle,
    pw.TextStyle valueStyle,
  ) {
    return pw.TableRow(
      children: [
        pw.Padding(
          padding: const pw.EdgeInsets.symmetric(vertical: 2.0),
          child: pw.Text(label, style: labelStyle),
        ),
        pw.Padding(
          padding: const pw.EdgeInsets.symmetric(vertical: 2.0),
          child: pw.Text(value, style: valueStyle),
        ),
      ],
    );
  }

  static pw.Widget _buildSectionHeader(String title, PdfColor ruleColor, PdfColor textColor) {
    return pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        pw.Text(
          title,
          style: pw.TextStyle(fontSize: 12, fontWeight: pw.FontWeight.bold, color: textColor),
        ),
        pw.SizedBox(height: 2),
        pw.Container(height: 1, color: ruleColor),
      ],
    );
  }

  static pw.Widget _buildTableHeaderCell(String text) {
    return pw.Padding(
      padding: const pw.EdgeInsets.all(5.0),
      child: pw.Text(
        text,
        style: pw.TextStyle(fontSize: 8.5, fontWeight: pw.FontWeight.bold),
      ),
    );
  }

  static pw.Widget _buildTableCell(String text, pw.TextStyle style) {
    return pw.Padding(
      padding: const pw.EdgeInsets.all(5.0),
      child: pw.Text(text, style: style),
    );
  }

  /// Formats the Drug/Dose cell for Section 5.
  ///
  /// Combined products (detected by a "COMBINED:<components>" sentinel stored
  /// in [HrtPhase.changeReason]) are rendered as:
  ///   "[drugName] (combined)"
  /// with the component string on a second line.
  ///
  /// Regular products use the standard "[drugName] [dose][unit]" format.
  static String _formatHrtDrugDose(HrtPhase phase) {
    // Sentinel: changeReason starts with "COMBINED:" on non-marker rows
    final reason = phase.changeReason ?? '';
    if (!phase.isDoseChangeMarker && reason.startsWith('COMBINED:')) {
      final components = reason.substring('COMBINED:'.length).trim();
      if (components.isNotEmpty) {
        return '${phase.drugName} (combined)\n$components';
      }
      return '${phase.drugName} (combined)';
    }
    return '${phase.drugName} ${phase.dose}${phase.unit}';
  }
}
